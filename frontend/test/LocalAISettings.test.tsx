import { fireEvent, render, screen, waitFor } from '@testing-library/react'
import { beforeEach, afterEach, expect, it, vi } from 'vitest'
import LocalAISettings from '../src/components/LocalAISettings'
import { readLocalAIConfig, saveLocalAIConfig } from '../src/lib/localAI'

beforeEach(() => { localStorage.clear(); sessionStorage.clear(); localStorage.setItem('user', JSON.stringify({ id: 7 })) })
afterEach(() => vi.unstubAllGlobals())
it('saves a key locally without any request and explains manual generation', () => {
  const fetch = vi.fn(); vi.stubGlobal('fetch', fetch)
  render(<LocalAISettings />)
  fireEvent.change(screen.getByLabelText('API Key'), { target: { value: 'local-secret' } })
  fireEvent.change(screen.getByLabelText(/Base URL/), { target: { value: 'https://provider.example/v1' } })
  fireEvent.change(screen.getByLabelText('Model'), { target: { value: 'model' } })
  fireEvent.click(screen.getByText('保存到本机'))
  expect(readLocalAIConfig()?.api_key).toBe('local-secret')
  expect(screen.getByRole('status').textContent).toContain('手动点击')
  expect(fetch).not.toHaveBeenCalled()
  expect((screen.getByLabelText(/API Key/) as HTMLInputElement).value).toBe('')
})
it('tests a saved key only when clicked and can delete it', async () => {
  saveLocalAIConfig({ api_key: 'local-secret', base_url: 'https://provider.example/v1', model: 'model' }, true)
  const fetch = vi.fn().mockResolvedValue(new Response(JSON.stringify({ choices: [{ message: { content: 'OK' }, finish_reason: 'stop' }] })))
  vi.stubGlobal('fetch', fetch)
  render(<LocalAISettings />)
  expect(fetch).not.toHaveBeenCalled()
  fireEvent.click(screen.getByText('测试连通性'))
  await waitFor(() => expect(screen.getByRole('status').textContent).toContain('测试通过'))
  expect(fetch).toHaveBeenCalledTimes(1)
  fireEvent.click(screen.getByText('清除本机配置'))
  expect(readLocalAIConfig()).toBeNull()
})
it('offers verified providers and fills the URL without calling or saving anything', () => {
  const fetch = vi.fn(); vi.stubGlobal('fetch', fetch)
  render(<LocalAISettings />)
  const select=screen.getByLabelText('AI 服务')
  expect(screen.getByRole('option',{name:'DeepSeek'})).toBeTruthy()
  expect(screen.getByRole('option',{name:'OpenAI'})).toBeTruthy()
  expect(screen.getByRole('option',{name:'自定义地址'})).toBeTruthy()
  expect((screen.getByRole('option',{name:/GLM · 智谱国内按量/}) as HTMLOptionElement).disabled).toBe(true)
  expect(screen.getByRole('option',{name:'Claude / Anthropic'})).toBeTruthy()
  fireEvent.change(select,{target:{value:'deepseek'}})
  const url=screen.getByLabelText(/Base URL/) as HTMLInputElement
  expect(url.value).toBe('https://api.deepseek.com')
  expect(url.readOnly).toBe(true)
  expect(readLocalAIConfig()).toBeNull()
  expect(fetch).not.toHaveBeenCalled()
  fireEvent.change(select,{target:{value:'custom'}})
  expect(url.readOnly).toBe(false)
})
it('recognizes a saved preset and requires a fresh key when switching provider', () => {
  saveLocalAIConfig({api_key:'old-local-key',base_url:'https://api.deepseek.com',model:'model'},true)
  render(<LocalAISettings />)
  expect((screen.getByLabelText('AI 服务') as HTMLSelectElement).value).toBe('deepseek')
  fireEvent.change(screen.getByLabelText(/API Key/),{target:{value:'new-key-for-old-provider'}})
  fireEvent.change(screen.getByLabelText('AI 服务'),{target:{value:'openai'}})
  expect((screen.getByLabelText(/API Key/) as HTMLInputElement).value).toBe('')
  fireEvent.click(screen.getByText('保存到本机'))
  expect(screen.getByRole('alert').textContent).toContain('重新输入')
  expect(readLocalAIConfig()?.base_url).toBe('https://api.deepseek.com')
})
it('retains an existing custom address and resets the selector when cleared', () => {
  saveLocalAIConfig({api_key:'key',base_url:'https://custom.example/v1',model:'model'},false)
  render(<LocalAISettings />)
  expect((screen.getByLabelText('AI 服务') as HTMLSelectElement).value).toBe('custom')
  expect((screen.getByLabelText(/Base URL/) as HTMLInputElement).value).toBe('https://custom.example/v1')
  fireEvent.change(screen.getByLabelText('AI 服务'),{target:{value:'deepseek'}})
  fireEvent.click(screen.getByText('清除本机配置'))
  expect((screen.getByLabelText('AI 服务') as HTMLSelectElement).value).toBe('custom')
  expect((screen.getByLabelText(/Base URL/) as HTMLInputElement).value).toBe('')
})
