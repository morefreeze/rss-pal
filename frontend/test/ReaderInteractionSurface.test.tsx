import { act, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { ReaderActionContext } from '../src/reader/ReaderActionContext'
import { ReaderInteractionSurface } from '../src/reader/ReaderInteractionSurface'
import type { ReaderActionContextValue } from '../src/reader/types'

function context(overrides: Partial<ReaderActionContextValue> = {}): ReaderActionContextValue {
  return {
    normalizeLink: (href) => {
      try {
        const url = new URL(href, 'https://reader.example/article')
        return /^https?:$/.test(url.protocol) ? url.href : null
      } catch {
        return null
      }
    },
    getLinkState: () => null,
    getActions: () => [{ id: 'add', label: '加入待抓取', run: vi.fn() }],
    ...overrides,
  }
}

function subject(markup = (
  <p>
    <span>Before </span><a href="/a">Alpha readable link</a>
    <span> middle </span><a href="/b">Beta link</a><span> after</span>
  </p>
), value = context()) {
  return render(
    <ReaderActionContext.Provider value={value}>
      <ReaderInteractionSurface articleKey="article-1">{markup}</ReaderInteractionSurface>
    </ReaderActionContext.Provider>,
  )
}

function select(start: Node, startOffset: number, end: Node, endOffset: number) {
  const range = document.createRange()
  range.setStart(start, startOffset)
  range.setEnd(end, endOffset)
  const selection = window.getSelection()!
  selection.removeAllRanges()
  selection.addRange(range)
}

afterEach(() => {
  vi.useRealTimers()
  vi.restoreAllMocks()
  window.getSelection()?.removeAllRanges()
})

describe('ReaderInteractionSurface desktop selection', () => {
  it('opens after pointerup and highlights the complete partially-selected link', () => {
    subject()
    const anchor = screen.getByRole('link', { name: 'Alpha readable link' })
    select(anchor.firstChild!, 6, anchor.firstChild!, 14)

    fireEvent.pointerUp(anchor, { pointerType: 'mouse' })

    expect(screen.getByRole('menu')).toBeTruthy()
    expect(anchor.classList.contains('reader-context-target')).toBe(true)
  })

  it('opens after a keyboard Selection stabilizes', () => {
    subject()
    const anchor = screen.getByRole('link', { name: 'Alpha readable link' })
    select(anchor.firstChild!, 2, anchor.firstChild!, 8)
    fireEvent.keyUp(anchor, { key: 'Shift' })
    expect(screen.getByRole('menu')).toBeTruthy()
    expect(anchor.classList.contains('reader-context-target')).toBe(true)
  })

  it('replaces a non-collapsed Selection on selectionchange but keeps a snapshot when menu focus collapses it', () => {
    subject()
    const [first, second] = screen.getAllByRole('link')
    select(first.firstChild!, 1, first.firstChild!, 4)
    fireEvent.pointerUp(first, { pointerType: 'mouse' })

    select(second.firstChild!, 1, second.firstChild!, 4)
    fireEvent(document, new Event('selectionchange'))
    expect(first.classList.contains('reader-context-target')).toBe(false)
    expect(second.classList.contains('reader-context-target')).toBe(true)

    window.getSelection()!.removeAllRanges()
    fireEvent(document, new Event('selectionchange'))
    expect(screen.getByRole('menu')).toBeTruthy()
    expect(second.classList.contains('reader-context-target')).toBe(true)
  })

  it('stays closed for pure text and highlights every selected link', () => {
    subject()
    const spans = document.querySelectorAll('span')
    select(spans[0].firstChild!, 0, spans[0].firstChild!, 3)
    fireEvent.pointerUp(spans[0], { pointerType: 'mouse' })
    expect(screen.queryByRole('menu')).toBeNull()

    select(spans[0].firstChild!, 1, spans[2].firstChild!, 2)
    fireEvent.pointerUp(spans[2], { pointerType: 'mouse' })
    expect(screen.getByRole('menu')).toBeTruthy()
    expect(document.querySelectorAll('a.reader-context-target')).toHaveLength(2)
  })

  it('never prevents the ordinary mouse context menu', () => {
    subject()
    const anchor = screen.getByRole('link', { name: 'Alpha readable link' })
    expect(fireEvent.contextMenu(anchor, { pointerType: 'mouse' })).toBe(true)
  })

  it('suppresses only the click generated by drag selection', () => {
    const clicked = vi.fn()
    subject(<p><a href="#ok" onClick={clicked}>Alpha readable link</a></p>)
    const anchor = screen.getByRole('link')
    select(anchor.firstChild!, 1, anchor.firstChild!, 5)
    fireEvent.pointerUp(anchor, { pointerType: 'mouse' })

    expect(fireEvent.click(anchor)).toBe(false)
    expect(clicked).not.toHaveBeenCalled()
    expect(fireEvent.click(anchor)).toBe(true)
    expect(clicked).toHaveBeenCalledTimes(1)
  })

  it('does not suppress an unrelated link click and clears suppression when closed', () => {
    const firstClick = vi.fn((event: React.MouseEvent) => event.preventDefault())
    const secondClick = vi.fn((event: React.MouseEvent) => event.preventDefault())
    subject(<p><a href="/a" onClick={firstClick}>First link</a> <a href="/b" onClick={secondClick}>Second link</a></p>)
    const [first, second] = screen.getAllByRole('link')
    select(first.firstChild!, 1, first.firstChild!, 4)
    fireEvent.pointerUp(first, { pointerType: 'mouse' })
    fireEvent.click(second)
    expect(secondClick).toHaveBeenCalledTimes(1)

    fireEvent.keyDown(screen.getByRole('menuitem'), { key: 'Escape' })
    fireEvent.click(first)
    expect(firstClick).toHaveBeenCalledTimes(1)
  })

  it('allows an ordinary link click when there was no selection', () => {
    const clicked = vi.fn((event: React.MouseEvent) => event.preventDefault())
    subject(<p><a href="/a" onClick={clicked}>Alpha readable link</a></p>)
    fireEvent.click(screen.getByRole('link'))
    expect(clicked).toHaveBeenCalledTimes(1)
  })

  it('closes and removes highlights on Escape or scroll', () => {
    subject()
    const anchor = screen.getByRole('link', { name: 'Alpha readable link' })
    select(anchor.firstChild!, 0, anchor.firstChild!, 3)
    fireEvent.pointerUp(anchor, { pointerType: 'mouse' })
    fireEvent.keyDown(screen.getByRole('menuitem'), { key: 'Escape' })
    expect(screen.queryByRole('menu')).toBeNull()
    expect(anchor.classList.contains('reader-context-target')).toBe(false)
    expect(document.activeElement).toBe(anchor)

    select(anchor.firstChild!, 0, anchor.firstChild!, 3)
    fireEvent.pointerUp(anchor, { pointerType: 'mouse' })
    fireEvent.scroll(window)
    expect(screen.queryByRole('menu')).toBeNull()
    expect(anchor.classList.contains('reader-context-target')).toBe(false)
  })

  it('replaces a target snapshot and cleans classes on unmount', () => {
    const { unmount } = subject()
    const [first, second] = screen.getAllByRole('link')
    select(first.firstChild!, 0, first.firstChild!, 2)
    fireEvent.pointerUp(first, { pointerType: 'mouse' })
    select(second.firstChild!, 0, second.firstChild!, 2)
    fireEvent.pointerUp(second, { pointerType: 'mouse' })
    expect(first.classList.contains('reader-context-target')).toBe(false)
    expect(second.classList.contains('reader-context-target')).toBe(true)
    unmount()
    expect(second.classList.contains('reader-context-target')).toBe(false)
  })
})

describe('ReaderInteractionSurface phone selection', () => {
  it('uses the unfocused toolbar on a landscape touch device wider than 640px', () => {
    const original = window.matchMedia
    vi.spyOn(window, 'matchMedia').mockImplementation(query => ({
      ...original(query), matches: query === '(pointer: coarse)',
    }))
    subject()
    const anchor = screen.getByRole('link', { name: 'Alpha readable link' })
    select(anchor.firstChild!, 1, anchor.firstChild!, 4)
    fireEvent(document, new Event('selectionchange'))
    expect(screen.getByRole('toolbar')).toBeTruthy()
    expect(document.activeElement).toBe(document.body)
    fireEvent.scroll(window)
    expect(screen.getByRole('toolbar')).toBeTruthy()
  })
  function phone() {
    const original = window.matchMedia
    vi.spyOn(window, 'matchMedia').mockImplementation((query) => ({
      ...original(query), matches: query === '(max-width: 640px)',
    }))
  }

  it('leaves link long press and its context menu to the browser', () => {
    phone()
    vi.useFakeTimers()
    subject()
    const anchor = screen.getByRole('link', { name: 'Alpha readable link' })
    fireEvent.pointerDown(anchor, { pointerType: 'touch', pointerId: 1 })
    act(() => vi.advanceTimersByTime(1500))
    expect(screen.queryByRole('menu')).toBeNull()
    expect(screen.queryByRole('toolbar')).toBeNull()
    expect(fireEvent.contextMenu(anchor, { pointerType: 'touch' })).toBe(true)
  })

  it('keeps the native selection and focus while showing capture at the bottom', () => {
    phone()
    subject()
    const [first, second] = screen.getAllByRole('link')
    select(first.firstChild!, 1, second.firstChild!, 3)
    const selected = window.getSelection()!.toString()
    fireEvent(document, new Event('selectionchange'))
    const toolbar = screen.getByRole('toolbar', { name: '选中链接操作' })
    expect(toolbar.classList.contains('reader-selection-toolbar')).toBe(true)
    expect(window.getSelection()!.toString()).toBe(selected)
    expect(document.activeElement).toBe(document.body)
    expect(first.classList.contains('reader-context-target')).toBe(true)
    expect(second.classList.contains('reader-context-target')).toBe(true)
  })

  it('allows handle adjustment, uses the new selection and supports explicit dismiss', () => {
    phone()
    const run = vi.fn()
    const getActions = vi.fn<ReaderActionContextValue['getActions']>(() => [{ id: 'add', label: '加入待抓取', run }])
    subject(undefined, context({ getActions }))
    const [first, second] = screen.getAllByRole('link')
    select(first.firstChild!, 0, first.firstChild!, 3)
    fireEvent(document, new Event('selectionchange'))
    fireEvent.pointerDown(second, { pointerType: 'touch', pointerId: 2 })
    expect(screen.getByRole('toolbar')).toBeTruthy()
    select(first.firstChild!, 0, second.firstChild!, 3)
    fireEvent(document, new Event('selectionchange'))
    expect(getActions.mock.lastCall?.[0].links).toHaveLength(2)
    fireEvent.click(screen.getByRole('button', { name: '关闭选中链接操作' }))
    expect(screen.queryByRole('toolbar')).toBeNull()
    expect(document.activeElement).toBe(document.body)
  })
})
